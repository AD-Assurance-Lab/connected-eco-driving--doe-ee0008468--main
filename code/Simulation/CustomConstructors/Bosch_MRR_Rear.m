classdef Bosch_MRR_Rear<handle
    % This constructor defines a Bosch MRR Front radar. The front radar has
    % two antennae and thus must be created as multiple sensors. Because these
    % sensors will see the same objects if they cover the same area, the
    % sensor will be modeled as having a very large FOV with detections
    % outside of a certain area being rejected.
    properties
        Name
        Sensor
        Data
        Location %[x,y,z] x,y in veh coord z in ref to ground (VS - TCS)
        Orientation %[i,j,k] (roll,pitch,yaw) veh (VS - VCS)
        LargeFOV %Range and FOV of bounding box
        LargeRange
        FOV %FOVs and Ranges of actual area
        Range
        X1 %bounding X and Y coordinates of the actual FOV
        Y1
        X2
        Y2
        SensorIndex %index of sensor relative to simulation vehicle
        Type=2; % 1 - Visual, 2 - Radar, 3 - LiDAR
    end
    methods
        function obj=Bosch_MRR_Rear(Name,Location,Orientation,SensorIndex)
            %Implicit main, can be generated with or without specific
            %imputs
            if nargin>0
                obj.Name=Name;
                obj.Location=Location;
                obj.Orientation=Orientation;
                obj.SensorIndex=SensorIndex;
            else %defaults
                obj.Name='Bosch_MRR_Rear';
                obj.Location=[0 0 1];
                obj.Orientation=[0 0 0];
                obj.SensorIndex=1;
            end
            %Bigger Box
            obj.LargeFOV=[150 25];
            obj.LargeRange=70;
            %Actual area
            obj.FOV=[70 10];
            obj.Range=[20 70];
            obj.X1=[obj.Location(1) -(obj.Range(1)-obj.Location(1))*cosd([-obj.FOV(1)/2:.1:obj.FOV(1)/2])];
            obj.Y1=[obj.Location(2) (obj.Range(1))*sind([-obj.FOV(1)/2:.1:obj.FOV(1)/2])];
            obj.X2=[obj.Location(1) -(obj.Range(2)-obj.Location(1))*cosd([-obj.FOV(2)/2:.1:obj.FOV(2)/2])];
            obj.Y2=[obj.Location(2) (obj.Range(2))*sind([-obj.FOV(2)/2:.1:obj.FOV(2)/2])];
            %Calls initilaization function
            obj.Initialize();
        end
        function BEP=PlotFOV(obj,BirdsEyePlot)
            if nargin<2
                BEP=birdsEyePlot();
            else
                BEP=BirdsEyePlot;
            end
            CAP{1}=coverageAreaPlotter(BEP,'FaceColor','red','EdgeColor','red','DisplayName','MRR Rear (LR)');
            CAP{2}=coverageAreaPlotter(BEP,'FaceColor','red','EdgeColor','red','DisplayName','MRR Rear (SR)');
            plotCoverageArea(CAP{1},obj.Sensor.SensorLocation,obj.Range(1),obj.Sensor.Yaw,obj.FOV(1));
            plotCoverageArea(CAP{2},obj.Sensor.SensorLocation,obj.Range(2),obj.Sensor.Yaw,obj.FOV(2));
        end
        function obj=RandomTestDataPlot(obj)
            %plot to show the selection algorithm
            dx=70*rand(1,100).*randi([-1 1],1,100);
            dy=30*rand(1,100).*randi([-1 1],1,100);
            in1=inpolygon(dx,dy,obj.X1,obj.Y1); %in polygon conditionals
            in2=inpolygon(dx,dy,obj.X2,obj.Y2);
            obj.PlotFOV();
            hold on
            patch(obj.X1,obj.Y1,'y')
            patch(obj.X2,obj.Y2,'g')
            for i=1:1:numel(in1)
                if any([in1(i) in2(i)])
                    plot(dx(i),dy(i),'ob')
                else
                    plot(dx(i),dy(i),'or')
                end
            end
            
        end
        function [ObjDets,ObjValid,Positions]=Detections(obj,TP,time,index,TWODKF)
            % This function handles detections generated by the sensor.
            % Because these detections are for teh large detection area
            % they are sorted by whether they fall into the smaller 
            % polygons of the actual area.
            [ObjDets,~,ObjValid]=obj.Sensor(TP,time); %detections from sensor
            Positions=[];
            j=0;
            for i = 1:1:numel(ObjDets)
                dx=ObjDets{i}.Measurement(1);% x and y position of the 
                % detection in ego vehicle coordinates
                dy=ObjDets{i}.Measurement(2);
                in1=inpolygon(dx,dy,obj.X1,obj.Y1); %in polygon conditionals
                in2=inpolygon(dx,dy,obj.X2,obj.Y2);      
                if any([in1 in2]) %if in either polygon
                    %logging various data for the detection
                    j=j+1;
                    obj.Data.(sprintf('%s_obj%i_%s',obj.Name,j,'dx'))(index)=ObjDets{i}.Measurement(1);
                    obj.Data.(sprintf('%s_obj%i_%s',obj.Name,j,'dy'))(index)=ObjDets{i}.Measurement(2);
                    obj.Data.(sprintf('%s_obj%i_%s',obj.Name,j,'vx'))(index)=ObjDets{i}.Measurement(3);
                    obj.Data.(sprintf('%s_obj%i_%s',obj.Name,j,'vy'))(index)=ObjDets{i}.Measurement(4);
                    obj.Data.(sprintf('%s_obj%i_%s',obj.Name,j,'ax'))(index)=ObjDets{i}.Measurement(5);
                    obj.Data.(sprintf('%s_obj%i_%s',obj.Name,j,'ay'))(index)=ObjDets{i}.Measurement(6);
                    Positions(j,:)=[ObjDets{i}.Measurement(1),ObjDets{i}.Measurement(2)];
                    if TWODKF==1
                        %2D Kalman Filter Stuff
                        ObjDets{i}.Measurement=[ObjDets{i}.Measurement(1),ObjDets{i}.Measurement(2)];
                        ObjDets{i}.MeasurementNoise = diag([100,100]);
                    end
                end
            end
        end
        function obj=Initialize(obj)
            obj.Sensor=radarDetectionGenerator(); %makes a radar sensor
            obj.Sensor.SensorIndex=obj.SensorIndex;                %Unique identifier of sensor
            obj.Sensor.UpdateInterval=.06;             %Required interval between sensor updates
            obj.Sensor.SensorLocation=[obj.Location(1) obj.Location(2)];          %Location of sensor center specified in
                                                 %vehicle coordinate system
            obj.Sensor.Height=obj.Location(3);                     %Sensor's mounting height from the ground
            obj.Sensor.Yaw=obj.Orientation(3);                        %Yaw angle of sensor mounted on ego
                                                 %vehicle
            obj.Sensor.Pitch=obj.Orientation(2);                      %Pitch angle of sensor mounted on ego
                                                 %vehicle
            obj.Sensor.Roll=obj.Orientation(1);                       %Roll angle of sensor mounted on ego
                                       %vehicle
            obj.Sensor.FieldOfView=obj.LargeFOV;                %Total angular field of view for radar
            obj.Sensor.MaxRange=obj.LargeRange;                   %Maximum detection range
            % obj.Sensor.RangeRateLimits            %Minimum and maximum range rates that can
                                       %be reported
            % obj.Sensor.DetectionProbability       %Detection probability
            % obj.Sensor.FalseAlarmRate             %Rate at which false alarms are reported
            % obj.Sensor.ReferenceRange             %Range where detection probability is
                                       %achieved
            % obj.Sensor.ReferenceRCS               %Target's radar cross section (RCS) at
                                       %which detection probability is achieved
            % obj.Sensor.RadarLoopGain              %Loop gain of radar (read-only)
            % obj.Sensor.AzimuthResolution          %Azimuthal resolution of radar
            % obj.Sensor.ElevationResolution        %Elevation resolution of radar
            % obj.Sensor.RangeResolution            %Range resolution of radar
            % obj.Sensor.RangeRateResolution        %Range rate resolution of radar
            % obj.Sensor.AzimuthBiasFraction        %Fractional azimuthal bias component of 
                                       %radar
            % obj.Sensor.ElevationBiasFraction      %Fractional elevation bias component of
                                       %radar
            % obj.Sensor.RangeBiasFraction          %Fractional range bias component of radar
            % obj.Sensor.RangeRateBiasFraction      %Fractional range rate bias component of
                                       %radar
            obj.Sensor.HasElevation=0;               %Enable elevation angle measurements
            % obj.Sensor.HasRangeRate               %Enable range rate measurements
            % obj.Sensor.HasNoise                   %Add noise to measurements
            % obj.Sensor.HasFalseAlarms             %Enable false detections
            % obj.Sensor.HasOcclusion               %Enable line-of-sight occlusion
            obj.Sensor.MaxNumDetectionsSource='Property';     %Source of maximum number of detections
            obj.Sensor.MaxNumDetections=32;           %Maximum number of reported detections
            % obj.Sensor.DetectionCoordinates       %Coordinate system used to report detections
            % obj.Sensor.ActorProfiles              %Profiles for all actors used to generate
            obj.Data=struct('empty',[]);
            NMessages=obj.Sensor.MaxNumDetections;
            SignalNames={'dx','dy','vx','vy','ax','ay'};
            for i=1:1:NMessages
                for j=1:1:numel(SignalNames)
                    c=SignalNames(j); s=c{:};
                    obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,s))=[];
                end
            end
        end
    end
end