classdef Bosch_MRR_Rear<handle
    % This constructor defines a Bosch MRR Front radar. The front radar has
    % two antennae and thus must be created as multiple sensors. Because these
    % sensors will see the same objects if they cover the same area, the
    % sensor will be modeled as having a very large FOV with detections
    % outside of a certain area being rejected.
    properties
        Name
        SensorSR
        SensorLR
        Data
        Location %[x,y,z] x,y in veh coord z in ref to ground (VS - TCS)
        Orientation %[i,j,k] (roll,pitch,yaw) veh (VS - VCS)
        FOV %FOVs and Ranges of actual area
        Range
        SensorIndex %index of sensor relative to simulation vehicle
        Type=2; % 1 - Visual, 2 - Radar, 3 - LiDAR
    end
    methods
        function obj=Bosch_MRR_Rear(Name,Location,Orientation,SensorIndex)
            %Implicit main, can be generated with or without specific
            %imputs
            if nargin>0
                obj.Name=Name;
                obj.Location=Location;
                obj.Orientation=Orientation;
                obj.SensorIndex=SensorIndex;
            else %defaults
                obj.Name='Bosch_MRR_Rear';
                obj.Location=[0 0 1];
                obj.Orientation=[0 0 0];
                obj.SensorIndex=1;
            end
            %Actual area
            obj.FOV=[150 20];
            obj.Range=[30 70];
            %Calls initilaization function
            obj.Initialize();
        end
        function BEP=PlotFOV(obj,BirdsEyePlot)
            if nargin<2
                BEP=birdsEyePlot();
            else
                BEP=BirdsEyePlot;
            end
            CAP{1}=coverageAreaPlotter(BEP,'FaceColor','red','EdgeColor','red','DisplayName','MRR Front (LR)');
            CAP{2}=coverageAreaPlotter(BEP,'FaceColor','red','EdgeColor','red','DisplayName','MRR Front (SR)');
            plotCoverageArea(CAP{1},obj.SensorLR.SensorLocation,obj.Range(1),obj.SensorLR.Yaw,obj.FOV(1));
            plotCoverageArea(CAP{2},obj.SensorSR.SensorLocation,obj.Range(2),obj.SensorSR.Yaw,obj.FOV(2));
        end
        function [ObjDets,ObjValid,Positions,newDetections]=Detections(obj,TP,time,index,KFDim)
            % This function handles detections generated by the sensor.
            % Because these detections are for teh large detection area
            % they are sorted by whether they fall into the smaller 
            % polygons of the actual area.
            [ObjDetsSR,~,ObjValidSR]=obj.SensorSR(TP,time); %detections from short range sensor
            [ObjDetsLR,~,ObjValidLR]=obj.SensorLR(TP,time); %detections from long range sensor
            Positions=[]; newDetections=0;
            for i = 1:1:numel(ObjDetsSR)
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'dx'))(index)=ObjDetsSR{i}.Measurement(1);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'dy'))(index)=ObjDetsSR{i}.Measurement(2);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'vx'))(index)=ObjDetsSR{i}.Measurement(3);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'vy'))(index)=ObjDetsSR{i}.Measurement(4);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'ax'))(index)=ObjDetsSR{i}.Measurement(5);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'ay'))(index)=ObjDetsSR{i}.Measurement(6);
                if (ObjDetsSR{i}.Measurement(1)^2+ObjDetsSR{i}.Measurement(2)^2)~=0
                    Positions=[Positions;ObjDetsSR{i}.Measurement(1),ObjDetsSR{i}.Measurement(2)];
                    newDetections=1;
                end
                ObjDetsSR{i}.Time=time;
                if KFDim==2
                    %2D Kalman Filter
                    ObjDetsSR{i}.Measurement=[ObjDetsSR{i}.Measurement(1),ObjDetsSR{i}.Measurement(2)];
%                     ObjDetsSR{i}.MeasurementNoise = ObjDetsSR{i}.MeasurementNoise(1:2,1:2);
                    ObjDetsSR{i}.MeasurementNoise = diag([100,100]);
                elseif KFDim==3
                    %3D Kalman Filter
                    ObjDetsSR{i}.Measurement=[ObjDetsSR{i}.Measurement(1),ObjDetsSR{i}.Measurement(2),ObjDetsSR{i}.Measurement(3)];
                    ObjDetsSR{i}.MeasurementNoise = diag([100,100,100]);
                end
            end
            for i = 1:1:numel(ObjDetsLR)
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'dx'))(index)=ObjDetsLR{i}.Measurement(1);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'dy'))(index)=ObjDetsLR{i}.Measurement(2);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'vx'))(index)=ObjDetsLR{i}.Measurement(3);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'vy'))(index)=ObjDetsLR{i}.Measurement(4);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'ax'))(index)=ObjDetsLR{i}.Measurement(5);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'ay'))(index)=ObjDetsLR{i}.Measurement(6);
                if (ObjDetsLR{i}.Measurement(1)^2+ObjDetsLR{i}.Measurement(2)^2)~=0
                    Positions=[Positions;ObjDetsLR{i}.Measurement(1),ObjDetsLR{i}.Measurement(2)];
                    newDetections=1;
                end
                ObjDetsLR{i}.Time=time;
                if KFDim==2
                    %2D Kalman Filter
                    ObjDetsLR{i}.Measurement=[ObjDetsLR{i}.Measurement(1),ObjDetsLR{i}.Measurement(2)];
%                     ObjDetsLR{i}.MeasurementNoise = ObjDetsLR{i}.MeasurementNoise(1:2,1:2);
                    ObjDetsLR{i}.MeasurementNoise = diag([100,100]);
                elseif KFDim==3
                    %3D Kalman Filter
                    ObjDetsLR{i}.Measurement=[ObjDetsLR{i}.Measurement(1),ObjDetsLR{i}.Measurement(2),ObjDetsLR{i}.Measurement(3)];
                    ObjDetsLR{i}.MeasurementNoise = diag([100,100,100]);
                end
            end
            ObjDets=[ObjDetsSR;ObjDetsLR]; ObjValid=[ObjValidSR ObjValidLR];
        end
        function obj=Initialize(obj)
            %Long Range Sensor
            obj.SensorLR=radarDetectionGenerator(); %makes a radar sensor
            obj.SensorLR.SensorIndex=obj.SensorIndex(1);                %Unique identifier of sensor
            obj.SensorLR.UpdateInterval=.06;             %Required interval between sensor updates
            obj.SensorLR.SensorLocation=[obj.Location(1) obj.Location(2)];          %Location of sensor center specified in
                                                 %vehicle coordinate system
            obj.SensorLR.Height=obj.Location(3);                     %SensorLR's mounting height from the ground
            obj.SensorLR.Yaw=obj.Orientation(3);                        %Yaw angle of sensor mounted on ego
                                                 %vehicle
            obj.SensorLR.Pitch=obj.Orientation(2);                      %Pitch angle of sensor mounted on ego
                                                 %vehicle
            obj.SensorLR.Roll=obj.Orientation(1);                       %Roll angle of sensor mounted on ego
                                       %vehicle
            obj.SensorLR.FieldOfView=[obj.FOV(1) 32];                %Total angular field of view for radar
            obj.SensorLR.MaxRange=obj.Range(1);                   %Maximum detection range
            % obj.SensorLR.RangeRateLimits            %Minimum and maximum range rates that can
                                       %be reported
            % obj.SensorLR.DetectionProbability       %Detection probability
            % obj.SensorLR.FalseAlarmRate             %Rate at which false alarms are reported
            % obj.SensorLR.ReferenceRange             %Range where detection probability is
                                       %achieved
            % obj.SensorLR.ReferenceRCS               %Target's radar cross section (RCS) at
                                       %which detection probability is achieved
            % obj.SensorLR.RadarLoopGain              %Loop gain of radar (read-only)
            % obj.SensorLR.AzimuthResolution          %Azimuthal resolution of radar
            % obj.SensorLR.ElevationResolution        %Elevation resolution of radar
            % obj.SensorLR.RangeResolution            %Range resolution of radar
            % obj.SensorLR.RangeRateResolution        %Range rate resolution of radar
            % obj.SensorLR.AzimuthBiasFraction        %Fractional azimuthal bias component of 
                                       %radar
            % obj.SensorLR.ElevationBiasFraction      %Fractional elevation bias component of
                                       %radar
            % obj.SensorLR.RangeBiasFraction          %Fractional range bias component of radar
            % obj.SensorLR.RangeRateBiasFraction      %Fractional range rate bias component of
                                       %radar
            obj.SensorLR.HasElevation=0;               %Enable elevation angle measurements
            % obj.SensorLR.HasRangeRate               %Enable range rate measurements
            % obj.SensorLR.HasNoise                   %Add noise to measurements
            % obj.SensorLR.HasFalseAlarms             %Enable false detections
            % obj.SensorLR.HasOcclusion               %Enable line-of-sight occlusion
            obj.SensorLR.MaxNumDetectionsSource='Property';     %Source of maximum number of detections
            obj.SensorLR.MaxNumDetections=12;           %Maximum number of reported detections
            % obj.SensorLR.DetectionCoordinates       %Coordinate system used to report detections
            % obj.SensorLR.ActorProfiles              %Profiles for all actors used to generate
            %Short Range SensorLR
            obj.SensorSR=radarDetectionGenerator(); %makes a radar sensor
            obj.SensorSR.SensorIndex=obj.SensorIndex(2);                %Unique identifier of sensor
            obj.SensorSR.UpdateInterval=.06;             %Required interval between sensor updates
            obj.SensorSR.SensorLocation=[obj.Location(1) obj.Location(2)];          %Location of sensor center specified in
                                                 %vehicle coordinate system
            obj.SensorSR.Height=obj.Location(3);                     %Sensor's mounting height from the ground
            obj.SensorSR.Yaw=obj.Orientation(3);                        %Yaw angle of sensor mounted on ego
                                                 %vehicle
            obj.SensorSR.Pitch=obj.Orientation(2);                      %Pitch angle of sensor mounted on ego
                                                 %vehicle
            obj.SensorSR.Roll=obj.Orientation(1);                       %Roll angle of sensor mounted on ego
                                       %vehicle
            obj.SensorSR.FieldOfView=[obj.FOV(2) 32];                %Total angular field of view for radar
            obj.SensorSR.MaxRange=obj.Range(2);                   %Maximum detection range
            % obj.SensorSR.RangeRateLimits            %Minimum and maximum range rates that can
                                       %be reported
            % obj.SensorSR.DetectionProbability       %Detection probability
            % obj.SensorSR.FalseAlarmRate             %Rate at which false alarms are reported
            % obj.SensorSR.ReferenceRange             %Range where detection probability is
                                       %achieved
            % obj.SensorSR.ReferenceRCS               %Target's radar cross section (RCS) at
                                       %which detection probability is achieved
            % obj.SensorSR.RadarLoopGain              %Loop gain of radar (read-only)
            % obj.SensorSR.AzimuthResolution          %Azimuthal resolution of radar
            % obj.SensorSR.ElevationResolution        %Elevation resolution of radar
            % obj.SensorSR.RangeResolution            %Range resolution of radar
            % obj.SensorSR.RangeRateResolution        %Range rate resolution of radar
            % obj.SensorSR.AzimuthBiasFraction        %Fractional azimuthal bias component of 
                                       %radar
            % obj.SensorSR.ElevationBiasFraction      %Fractional elevation bias component of
                                       %radar
            % obj.SensorSR.RangeBiasFraction          %Fractional range bias component of radar
            % obj.SensorSR.RangeRateBiasFraction      %Fractional range rate bias component of
                                       %radar
            obj.SensorSR.HasElevation=0;               %Enable elevation angle measurements
            % obj.SensorSR.HasRangeRate               %Enable range rate measurements
            % obj.SensorSR.HasNoise                   %Add noise to measurements
            % obj.SensorSR.HasFalseAlarms             %Enable false detections
            % obj.SensorSR.HasOcclusion               %Enable line-of-sight occlusion
            obj.SensorSR.MaxNumDetectionsSource='Property';     %Source of maximum number of detections
            obj.SensorSR.MaxNumDetections=20;           %Maximum number of reported detections
            % obj.SensorSR.DetectionCoordinates       %Coordinate system used to report detections
            % obj.SensorSR.ActorProfiles              %Profiles for all actors used to generate
            obj.Data=struct('empty',[]);
            NMessages=obj.SensorSR.MaxNumDetections+obj.SensorLR.MaxNumDetections;
            SignalNames={'dx','dy','vx','vy','ax','ay'};
            for i=1:1:NMessages
                for j=1:1:numel(SignalNames)
                    c=SignalNames(j); s=c{:};
                    obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,s))=[];
                end
            end
        end
    end
end