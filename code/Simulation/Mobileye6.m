classdef Mobileye6<handle
    properties
        Name
        Sensor
        Data
        Location %[x,y,z] x,y in veh coord z in ref to ground (VS - TCS)
        Orientation %[i,j,k] (roll,pitch,yaw) veh (VS - VCS)
        Range
        SensorIndex %index of sensor relative to simulation vehicle
        Type=1; % 1 - Visual, 2 - Radar, 3 - LiDAR
    end
    methods
        function obj=Mobileye6(Name,Location,Orientation,SensorIndex)
            if nargin>0
                obj.Name=Name;
                obj.Location=Location;
                obj.Orientation=Orientation;
                obj.SensorIndex=SensorIndex;
            else
                obj.Name='Mobileye6';
                obj.Location=[0 0 1];
                obj.Orientation=[0 0 0];
                obj.SensorIndex=1;
            end
            obj.Range=180;
            obj.Initialize();
        end
        function BEP=PlotFOV(obj,BirdsEyePlot)
            if nargin<2
                BEP=birdsEyePlot();
            else
                BEP=BirdsEyePlot;
            end
            CAP{1}=coverageAreaPlotter(BEP,'FaceColor','blue','EdgeColor','blue','DisplayName','Mobileye6');
            plotCoverageArea(CAP{1},obj.Sensor.SensorLocation,obj.Sensor.MaxRange,obj.Sensor.Yaw,obj.Sensor.FieldOfView(1));
        end
        function [ObjDets,ObjValid,LBDets,LBValid,Positions,newDetections]=Detections(obj,TP,LB,time,index,KFDim)
            [ObjDets,~,ObjValid,LBDets,~,LBValid]=obj.Sensor(TP,LB,time);
            obj.Data.curvature(index)=LBDets.LaneBoundaries(1).Curvature;
            obj.Data.heading(index)=LBDets.LaneBoundaries(1).HeadingAngle;
            obj.Data.offset(index)=LBDets.LaneBoundaries(1).LateralOffset;
            Positions=[]; newDetections=0;
            for i = 1:1:numel(ObjDets)
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'dx'))(index)=ObjDets{i}.Measurement(1);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'dy'))(index)=ObjDets{i}.Measurement(2);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'vx'))(index)=ObjDets{i}.Measurement(3);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'vy'))(index)=ObjDets{i}.Measurement(4);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'ax'))(index)=ObjDets{i}.Measurement(5);
                obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,'ay'))(index)=ObjDets{i}.Measurement(6);
                ObjDets{i}.Time=time;
                if (ObjDets{i}.Measurement(1)^2+ObjDets{i}.Measurement(2)^2)~=0
                    Positions=[Positions;ObjDets{i}.Measurement(1),ObjDets{i}.Measurement(2)];
                    newDetections=1;
                end
                if KFDim==2
                    %2D Kalman Filter
                    ObjDets{i}.Measurement=[ObjDets{i}.Measurement(1),ObjDets{i}.Measurement(2)];
                    ObjDets{i}.MeasurementNoise = diag([2,2]);
                    ObjDets{i}.ObjectAttributes{1}.SNR = NaN;
                elseif KFDim==3
                    %3D Kalman Filter
                    ObjDets{i}.Measurement=[ObjDets{i}.Measurement(1),ObjDets{i}.Measurement(2),ObjDets{i}.Measurement(3)];
                    ObjDets{i}.MeasurementNoise = diag([2,2,2]);
                    ObjDets{i}.ObjectAttributes{1}.SNR = NaN;
                end
            end
        end
        function obj=Initialize(obj)
            %vision sensor (Mobileye)
            obj.Sensor=visionDetectionGenerator();
            obj.Sensor.DetectorOutput='Lanes and Objects';             %Types of detections generated by sensor
            obj.Sensor.SensorIndex=obj.SensorIndex;                %Unique identifier for sensor
            obj.Sensor.UpdateInterval=.1;            %Required interval between sensor updates
            obj.Sensor.SensorLocation=[obj.Location(1) obj.Location(2)];          %Location of sensor center specified in
                                                 %vehicle coordinate system
            obj.Sensor.Height=obj.Location(3);                     %Sensor's mounting height from the ground
            obj.Sensor.Yaw=obj.Orientation(3);                        %Yaw angle of sensor mounted on ego
                                                 %vehicle
            obj.Sensor.Pitch=obj.Orientation(2);                      %Pitch angle of sensor mounted on ego
                                                 %vehicle
            obj.Sensor.Roll=obj.Orientation(1);                       %Roll angle of sensor mounted on ego
                                                 %vehicle
            % obj.Sensor.Intrinsics                 %Sensor's intrinsic camera parameters
            % obj.Sensor.FieldOfView               %Total angular field of view for sensor
                                                 %(read-only)
            obj.Sensor.MaxRange=obj.Range;                  %Maximum detection range
            obj.Sensor.MaxSpeed=500;                   %Maximum detectable object speed
            % obj.Sensor.MaxAllowedOcclusion        %Maximum allowed occlusion for detector
            obj.Sensor.DetectionProbability=.9;       %Probability of detecting a target
            obj.Sensor.FalsePositivesPerImage=.1;    %Number of false positives per image
            obj.Sensor.MinObjectImageSize=[5 5];        %Minimum image size of an object that can
                                                 %be detected
            % obj.Sensor.BoundingBoxAccuracy        %Bounding box accuracy
            % obj.Sensor.ProcessNoiseIntensity      %Noise intensity used to filter position
                                                 %and velocity measurements
            % obj.Sensor.HasNoise                   %Add noise to measurements
            obj.Sensor.MaxNumDetectionsSource='Property';     %Source of maximum number of detections
            obj.Sensor.MaxNumDetections=3;           %Maximum number of reported detections
            % obj.Sensor.DetectionCoordinates       %Coordinate system used to report vision
                                                 %detections
            % obj.Sensor.LaneUpdateInterval         %Required interval between lane detection
                                                 %updates
            obj.Sensor.MinLaneImageSize=[1 1];           %Minimum lane size in image
            % obj.Sensor.LaneBoundaryAccuracy       %Lane boundary accuracy
            obj.Sensor.MaxNumLanesSource='Property';          %Source of maximum number of reported
                                                 %lanes
            obj.Sensor.MaxNumLanes=3;                %Maximum number of reported lanes
            % obj.Sensor.ActorProfiles              %Physical characteristics for all actors
            obj.Data=struct('empty',[],'heading',[],'curvature',[],'offset',[]);
            NMessages=obj.Sensor.MaxNumDetections;
            SignalNames={'dx','dy','vx','vy','ax','ay'};
            for i=1:1:NMessages
                for j=1:1:numel(SignalNames)
                    c=SignalNames(j); s=c{:};
                    obj.Data.(sprintf('%s_obj%i_%s',obj.Name,i,s))=[];
                end
            end
        end
    end
end